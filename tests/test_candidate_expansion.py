"""Expansion plumbing uses artificial fixtures; real local candidate artifacts are optional."""

import importlib.util
import json
import sys
from collections import Counter
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from test_provisional_annotations import artificial_rows

from jais_guard.annotations import audit_report, connection, import_candidates, save_annotation

ROOT = Path(__file__).resolve().parents[1]


def preparation_module():
    spec = importlib.util.spec_from_file_location(
        "expansion_preparation", ROOT / "scripts/prepare_candidates.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_generation_batches_have_independent_frozen_audits(tmp_path):
    module = preparation_module()
    path = tmp_path / "annotations.sqlite3"
    old = artificial_rows(1, prefix="previous")
    import_candidates(old, path)
    save_annotation(old[0]["id"], label="VALID", flagged=False, notes="Preserve", path=path)
    with connection(path) as db:
        original = [tuple(r) for r in db.execute("SELECT * FROM annotations")]
        history = [tuple(r) for r in db.execute("SELECT * FROM revisions")]
    new = []
    for batch in ("generation-a", "generation-b"):
        rows = artificial_rows(6, prefix=batch)
        for row in rows:
            row["collection_batch"] = row["generation"]["batch_id"]
        new.extend(rows)
    module.import_expansion(new, path, policy_version="provisional-v1")
    reports = audit_report(path)
    assert len(reports) == 2
    assert {r["batch_id"] for r in reports} == {"generation-a", "generation-b"}
    assert all(r["population"] == r["sampled"] == 6 and r["status"] == "pending" for r in reports)
    with connection(path) as db:
        assert [tuple(r) for r in db.execute("SELECT * FROM annotations")] == original
        assert [tuple(r) for r in db.execute("SELECT * FROM revisions")] == history


def test_accidental_generation_batch_merging_is_rejected_before_import(tmp_path):
    module = preparation_module()
    path = tmp_path / "annotations.sqlite3"
    with connection(path):
        pass
    rows = artificial_rows(2)
    for row in rows:
        row["collection_batch"] = "merged-generation-batches"
    with pytest.raises(ValueError, match="must not be merged"):
        module.import_expansion(rows, path, policy_version="provisional-v1")
    with connection(path) as db:
        assert db.execute("SELECT COUNT(*) FROM candidates").fetchone()[0] == 0
        assert db.execute("SELECT COUNT(*) FROM audit_groups").fetchone()[0] == 0


def test_local_700_collection_counts_provenance_and_reconstruction():
    folder = ROOT / "data/milestone700_v1"
    if not (folder / "candidates.jsonl").exists():
        pytest.skip(
            "Unreviewed expansion artifacts are local, not downloaded or generated by tests"
        )
    saved = [json.loads(line) for line in (folder / "candidates.jsonl").read_text().splitlines()]
    assert len(saved) == 400
    assert Counter(r["intended_label"] for r in saved) == {"VALID": 187, "GIBBERISH": 213}
    assert Counter(r["difficulty"] for r in saved if r["intended_label"] == "GIBBERISH") == {
        "easy": 96,
        "medium": 85,
        "hard": 32,
    }
    assert all(r["partition"] == "train" for r in saved)
    ids = {r["id"] for r in saved}
    assert all(r["generation"].get("parent_id") not in ids for r in saved)
    rebuilt = preparation_module().expansion_candidates(folder)
    fields = ("id", "input_text", "intended_label", "difficulty", "family_id", "collection_batch")
    assert {tuple(r[k] for k in fields) for r in saved} == {
        tuple(r[k] for k in fields) for r in rebuilt
    }
    for r in saved:
        if r["source_method"] == "codex":
            assert r["collection_batch"] == r["generation"]["batch_id"]
            batch = json.loads((ROOT / r["generation"]["instructions_file"]).read_text())
            assert 5 <= len(batch["candidates"]) <= 10
            assert batch["instructions"] and "model_id" in batch["available_model_metadata"]
